// Pure route-contract checks: no browser, source or model traffic.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../web/package.json', import.meta.url));
const { build } = require('esbuild');
const result = await build({ entryPoints: [fileURLToPath(new URL('../web/src/state.ts', import.meta.url))], bundle: true, write: false, format: 'esm', platform: 'browser', define: { 'process.env.NODE_ENV': '"production"' } });
const { parseRoute, routeUrl, nextRoute } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const base = parseRoute('');
assert.equal(routeUrl(base), '/');
assert.equal(routeUrl({...base,view:'sources'}), '/?view=sources');
assert.equal(routeUrl({...base,view:'workbench'}), '/?view=processing');
assert.equal(routeUrl({...base,messageKey:'124'}), '/?m=124');
const legacy = parseRoute(`?view=investigate&scope=${encodeURIComponent(JSON.stringify(base.scope))}&evidence=telegram%3A1%3A-1002%3A42&revision=sha256%3Aabc`);
assert.equal(legacy.evidence,'telegram:1:-1002:42');
assert.deepEqual(legacy.scope,base.scope);
assert.equal(routeUrl({...legacy,messageKey:'124'}),'/?m=124');
const scoped = {...base,messageKey:'12',scope:{...base.scope,source_ids:['x:user:1','telegram:2:3'],include_unlocated:false,query:'Port & café',time_basis:'acquisition_time',from:'2026-09-01T00:00:00Z',to:'2026-09-12T00:00:00Z',bbox:[170,-10,-170,10],publication_id:'publication:fixture',content_view:'signals',related_key:'city/day'}};
assert.deepEqual(parseRoute(routeUrl(scoped).slice(1)).scope,scoped.scope);
assert.equal(parseRoute('?m=124').messageKey,'124');
assert.equal(base.scope.content_view,'events');
assert.equal(routeUrl(parseRoute('?feed=events')),'/');
assert.equal(routeUrl(parseRoute('?feed=all')),'/?feed=all');
assert.equal(parseRoute('?feed=events').scope.content_view,'events');
assert.equal(routeUrl({...base,scope:{...base.scope,event_type:'strike'}}),'/?type=strike');
assert.equal(parseRoute('?type=strike').scope.event_type,'strike');
assert.equal(parseRoute('?feed=all').scope.content_view,'all');
const oldScope={...base.scope,content_view:'all'};
delete oldScope.event_type;
assert.equal(parseRoute(`?scope=${encodeURIComponent(JSON.stringify(oldScope))}`).scope.content_view,'all');
assert.equal(parseRoute('?type=unknown').invalidScope,true);
assert.equal(parseRoute('?view=workbench').view,'workbench');
for (const bad of ['?scope=%7Bbad','?feed=garbage','?bbox=1,2,3','?time=garbage','?located=garbage']) assert.equal(parseRoute(bad).invalidScope,true,bad);
const selected={...base,evidence:'old',revision:'v1',messageKey:'12'};
assert.equal(nextRoute(selected,{evidence:null,revision:null}).messageKey,null);
assert.equal(nextRoute(selected,{revision:'v2'}).messageKey,null);
assert.equal(nextRoute(selected,{scope:{...base.scope,content_view:'signals'}}).messageKey,'12');
assert.equal(nextRoute(base,{evidence:'old',revision:'v1',messageKey:'12'}).messageKey,'12');
for (const preset of ['1h','2h','4h','8h','24h','1w']) {
  const rolling=parseRoute(`?range=${preset}`);
  assert.equal(rolling.invalidScope,false);
  assert.equal(rolling.window,preset);
  assert.equal(routeUrl(rolling),`/?range=${preset}`);
  assert.equal(rolling.scope.from,null);
  const paused=nextRoute(rolling,{scope:{...rolling.scope,from:'2026-09-12T10:00:00.000Z',to:'2026-09-12T11:00:00.000Z'}});
  assert.equal(paused.window,null);
  assert.deepEqual(parseRoute(routeUrl(paused).slice(1)),paused);
  assert.equal(nextRoute(rolling,{scope:{...rolling.scope,query:'test'}}).window,preset);
  assert.equal(routeUrl(nextRoute(paused,{window:preset})),`/?range=${preset}`);
}
assert.equal(parseRoute('?range=tomorrow').invalidScope,true);
assert.equal(parseRoute('?range=1h&from=2026-09-12T10:00:00Z').invalidScope,true);
console.log(JSON.stringify({outcome:'passed',default_url:'/',message_url:'/?m=124',legacy_links:true,scope_roundtrip:true,invalid_scope_disclosed:true,revision_switch_clears_old_key:true}));
